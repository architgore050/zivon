"""F10 admin data layer: aggregate-only reads over the product DB (the same
Postgres schema the core backend owns) plus the eval evidence directory.

The dashboard's `ZIVON_LOG_DSN` IS the backend DB DSN (`docs/deployment/
secrets.md`: one `zivon` database; `log_events` and the product tables share
the schema), so the F10 panels read the product tables through a second,
independent connection pool (`ProductStore`) resolved from `ZIVON_PRODUCT_DSN`
with a fallback to `ZIVON_LOG_DSN`. A source that cannot be reached is an
honest per-panel error, never a fake empty table — the same rule as
`queries.LogStore`.

Privacy contract (NFR-30, F-OPS-ADM-01 AC-4, features.md SCR-ADM-01):
aggregate-only panels. The student free-text columns (`problem_report.text`,
`speaking_attempt.transcript`) are NEVER selected, user emails and user ids
are never selected, and device pseudonyms are never rendered. The queries
below are the enforcement, and the tests pin it.

Tests seed fixtures by injecting a stub connection (`ProductStore(
connection=...)`) — the SQL stays the contract, exactly like
`queries.LogStore`.
"""

from __future__ import annotations

import datetime
import json
import os
import re
import threading
import uuid
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

REPORT_STATUSES = ("open", "fixed", "shipped_next_run")
REPORT_CATEGORIES = ("wrong_physics", "bad_translation", "broken_sim", "other")


def _utc_now_iso() -> str:
    now = datetime.datetime.now(datetime.UTC)
    return now.strftime("%Y-%m-%dT%H:%M:%S.") + f"{now.microsecond // 1000:03d}Z"


# Eval run ids are generated by evals/runner.py as
# "eval-<suite>-<UTC stamp>-<sha>-<suffix>" — lowercase hex plus UPPERCASE
# T/Z in the timestamp part, so the slug set is wider than factory run ids.
# A route param can never carry separators, "..", or traversal into the
# filesystem lookups (CodeQL py/path-injection): the regex rejects
# non-slug ids and the directory join matches server-controlled entry names
# by string equality (no Path is built from the user value).
_EVAL_RUN_ID_ALLOWED = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$")


def eval_runs_dir() -> Path:
    return Path(os.environ.get("ZIVON_EVAL_RUNS_DIR", "evals_runs"))


def _load_json(value: Any, default: Any) -> Any:
    """JSONB arrives as a dict from psycopg, as TEXT from SQLite."""
    if isinstance(value, (dict, list)) or value is None:
        return value if value is not None else default
    try:
        return json.loads(value)
    except (json.JSONDecodeError, TypeError):
        return default


def _product_dsn() -> str:
    """`ZIVON_PRODUCT_DSN` wins; the log DSN is the fallback because the
    log store and the product tables share the backend database
    (docs/deployment/secrets.md)."""
    return (
        os.environ.get("ZIVON_PRODUCT_DSN", "").strip()
        or os.environ.get("ZIVON_LOG_DSN", "").strip()
    )


# Separate thread-local from queries._CONNECTIONS: the two stores can carry
# different DSNs and must not evict each other's handle (FastAPI runs sync
# endpoints on a thread pool — connections never cross threads).
_PRODUCT_CONNECTIONS = threading.local()


def _cached_product_connection() -> tuple[str | None, Any | None]:
    return (
        getattr(_PRODUCT_CONNECTIONS, "dsn", None),
        getattr(_PRODUCT_CONNECTIONS, "conn", None),
    )


def _drop_product_connection(conn: Any) -> None:
    cached_dsn, cached = _cached_product_connection()
    if cached is conn:
        _PRODUCT_CONNECTIONS.dsn = None  # type: ignore[attr-defined]
        _PRODUCT_CONNECTIONS.conn = None  # type: ignore[attr-defined]
        del cached_dsn
    try:
        conn.close()
    except Exception as exc:  # noqa: BLE001 — a broken handle must not break the view
        del exc


@dataclass
class ProductStore:
    """Aggregate reads over the core-backend tables for the F10 panels.
    Same honesty contract as `LogStore`: every failure degrades to
    `unreachable` / an empty result plus `error`, and the view renders it."""

    connection: Any = None
    error: str | None = None

    @classmethod
    def from_env(cls) -> ProductStore:
        dsn = _product_dsn()
        if not dsn:
            return cls(connection=None, error=None)  # fallback mode: honest
        cached_dsn, cached = _cached_product_connection()
        if cached is not None and cached_dsn == dsn:
            return cls(connection=cached)
        try:
            import psycopg

            conn = psycopg.connect(dsn, autocommit=True)
        except Exception as exc:  # noqa: BLE001 — degrade, say so on the page
            return cls(connection=None, error=str(exc)[:200])
        _PRODUCT_CONNECTIONS.dsn = dsn  # type: ignore[attr-defined]
        _PRODUCT_CONNECTIONS.conn = conn  # type: ignore[attr-defined]
        return cls(connection=conn)

    @property
    def reachable(self) -> bool:
        return self.connection is not None

    def _fetchall(self, sql: str, params: tuple[Any, ...] = ()) -> list[dict[str, Any]]:
        if self.connection is None:
            return []
        try:
            with self.connection.cursor() as cur:
                cur.execute(sql, params)
                description = cur.description if cur.description else []
                columns = [getattr(c, "name", c[0]) for c in description]
                return [dict(zip(columns, row)) for row in cur.fetchall()]
        except Exception as exc:  # noqa: BLE001 — a panel never crashes the page
            self.error = self.error or str(exc)[:200]
            _drop_product_connection(self.connection)
            return []

    def _fetchone(
        self, sql: str, params: tuple[Any, ...] = ()
    ) -> dict[str, Any] | None:
        rows = self._fetchall(sql, params)
        return rows[0] if rows else None

    def _execute(self, sql: str, params: tuple[Any, ...] = ()) -> bool:
        if self.connection is None:
            self.error = self.error or "product store unreachable"
            return False
        try:
            with self.connection.cursor() as cur:
                cur.execute(sql, params)
            return True
        except Exception as exc:  # noqa: BLE001 — the view reports it honestly
            self.error = self.error or str(exc)[:200]
            _drop_product_connection(self.connection)
            return False

    # ----------------------------------------------------- content coverage
    def content_coverage(self) -> dict[str, Any]:
        """Published-page coverage: pages per class, version statuses, live
        pointers per locale, translation bundles, narration assets."""
        pages = self._fetchall(
            """
            SELECT class_level, COUNT(*) AS pages
            FROM content_page GROUP BY class_level ORDER BY class_level
            """
        )
        versions = self._fetchall(
            """
            SELECT class_level, status, COUNT(*) AS versions
            FROM page_version GROUP BY class_level, status
            ORDER BY class_level, status
            """
        )
        live = self._fetchall(
            """
            SELECT class_level, locale, COUNT(*) AS live_pages
            FROM live_pointer GROUP BY class_level, locale
            ORDER BY class_level, locale
            """
        )
        bundles = self._fetchall(
            """
            SELECT locale, COUNT(*) AS bundles,
                   SUM(CASE WHEN reviewed_flag THEN 1 ELSE 0 END) AS reviewed,
                   SUM(CASE WHEN status = 'published' THEN 1 ELSE 0 END) AS published
            FROM language_bundle GROUP BY locale ORDER BY locale
            """
        )
        narration = self._fetchall(
            """
            SELECT locale, COUNT(*) AS assets, COUNT(DISTINCT course_id) AS courses
            FROM narration_asset GROUP BY locale ORDER BY locale
            """
        )
        return {
            "pages": pages,
            "versions": versions,
            "live": live,
            "bundles": bundles,
            "narration": narration,
        }

    # -------------------------------------------------- question-bank health
    def question_bank_health(self) -> dict[str, Any]:
        """Aggregate bank shape: counts by the bank's own axes + pack gates
        + concept coverage gaps. Never item rows — no prompts, no answers."""
        by_status = self._fetchall(
            "SELECT status, COUNT(*) AS n FROM question_bank GROUP BY status ORDER BY status"
        )
        by_type = self._fetchall(
            "SELECT type, COUNT(*) AS n FROM question_bank GROUP BY type ORDER BY type"
        )
        by_difficulty = self._fetchall(
            """
            SELECT difficulty, COUNT(*) AS n FROM question_bank
            GROUP BY difficulty ORDER BY difficulty
            """
        )
        by_language = self._fetchall(
            "SELECT language, COUNT(*) AS n FROM question_bank GROUP BY language ORDER BY language"
        )
        by_class = self._fetchall(
            """
            SELECT class_level, COUNT(*) AS n FROM question_bank
            GROUP BY class_level ORDER BY class_level
            """
        )
        packs = self._fetchall(
            """
            SELECT kind, gate_verdict, COUNT(*) AS n FROM assessment_pack
            GROUP BY kind, gate_verdict ORDER BY kind, gate_verdict
            """
        )
        prompts = self._fetchall(
            "SELECT status, COUNT(*) AS n FROM speaking_prompt GROUP BY status ORDER BY status"
        )
        prompt_languages = self._fetchall(
            """
            SELECT language, COUNT(*) AS n FROM speaking_prompt
            GROUP BY language ORDER BY language
            """
        )
        concept_gaps = self._fetchall(
            """
            SELECT c.chapter_id AS chapter_id, COUNT(*) AS concepts_without_questions
            FROM concept c
            LEFT JOIN question_bank q
              ON q.concept_id = c.concept_id AND q.status IN ('reviewed', 'published')
            WHERE q.question_id IS NULL
            GROUP BY c.chapter_id
            ORDER BY concepts_without_questions DESC, c.chapter_id
            LIMIT 20
            """
        )
        priors = self._fetchone("SELECT COUNT(*) AS n FROM topic_time_prior")
        return {
            "by_status": by_status,
            "by_type": by_type,
            "by_difficulty": by_difficulty,
            "by_language": by_language,
            "by_class": by_class,
            "packs": packs,
            "prompts": prompts,
            "prompt_languages": prompt_languages,
            "concept_gaps": concept_gaps,
            "time_priors": int(priors["n"]) if priors else 0,
        }

    # ------------------------------------------------ series / blueprint status
    def series_status(self) -> dict[str, Any]:
        """The six-series catalogue per class with test/question counts, plus
        the exam/series packs the E1-E4 pipeline imported (blueprint
        volumes live in their `counts` JSON — aggregate numbers only)."""
        series = self._fetchall(
            """
            SELECT s.series_id, s.slug, s.class_level, s.kind, s.title, s.status,
                   s.language_set,
                   (SELECT COUNT(*) FROM test t WHERE t.series_id = s.series_id) AS tests,
                   (
                       SELECT COUNT(*) FROM test_question tq
                       JOIN test t2 ON t2.test_id = tq.test_id
                       WHERE t2.series_id = s.series_id
                   ) AS questions
            FROM test_series s
            ORDER BY s.class_level, s.kind, s.slug
            """
        )
        for row in series:
            row["language_set"] = _load_json(row.get("language_set"), [])
        packs = self._fetchall(
            """
            SELECT pack_id, kind, chapter_id, class_level, pack_version,
                   gate_verdict, counts, imported_at
            FROM assessment_pack
            WHERE kind IN ('exam', 'series')
            ORDER BY imported_at DESC
            LIMIT 20
            """
        )
        for row in packs:
            row["counts"] = _load_json(row.get("counts"), {})
        return {"series": series, "packs": packs}

    # ------------------------------------------------------- content-quality debt
    def quality_debt(self) -> dict[str, Any]:
        """The debt ledger: items waiting on review, failed gates,
        unreviewed bundles, unpublished pages, open content reports."""
        bank = self._fetchone(
            """
            SELECT
              COUNT(*) AS total,
              SUM(CASE WHEN status = 'draft' THEN 1 ELSE 0 END) AS drafts,
              SUM(CASE WHEN status = 'retired' THEN 1 ELSE 0 END) AS retired,
              SUM(CASE WHEN misconception IS NOT NULL THEN 1 ELSE 0 END)
                AS misconception_flagged,
              SUM(CASE WHEN review_mode = 'judged' THEN 1 ELSE 0 END) AS judged_mode,
              SUM(CASE WHEN review_mode = 'human' THEN 1 ELSE 0 END) AS human_mode
            FROM question_bank
            """
        )
        failing_packs = self._fetchall(
            """
            SELECT kind, COUNT(*) AS failing FROM assessment_pack
            WHERE gate_verdict = 'fail' GROUP BY kind ORDER BY kind
            """
        )
        unreviewed_bundles = self._fetchall(
            """
            SELECT locale, COUNT(*) AS unreviewed FROM language_bundle
            WHERE NOT reviewed_flag GROUP BY locale ORDER BY locale
            """
        )
        unpublished_pages = self._fetchone(
            """
            SELECT COUNT(*) AS pages_without_live FROM content_page cp
            WHERE NOT EXISTS (
                SELECT 1 FROM live_pointer lp
                WHERE lp.course_id = cp.course_id AND lp.class_level = cp.class_level
            )
            """
        )
        open_content_reports = self._fetchall(
            """
            SELECT category, COUNT(*) AS n FROM problem_report
            WHERE status = 'open'
              AND category IN ('wrong_physics', 'bad_translation')
            GROUP BY category ORDER BY category
            """
        )
        return {
            "bank": bank or {},
            "failing_packs": failing_packs,
            "unreviewed_bundles": unreviewed_bundles,
            "pages_without_live": int(unpublished_pages["pages_without_live"])
            if unpublished_pages
            else 0,
            "open_content_reports": open_content_reports,
        }

    # --------------------------------------------------- users (support only)
    def users_overview(self) -> dict[str, Any]:
        """Account-support aggregates + the deletion-request queue. No emails,
        no user ids, no device pseudonyms, no performance columns — the
        student-facing delete/export flows live in `web` / `/v1/me`."""
        by_role = self._fetchall(
            """
            SELECT role, COUNT(*) AS n FROM users
            WHERE deleted_at IS NULL GROUP BY role ORDER BY role
            """
        )
        verified = self._fetchone(
            """
            SELECT COUNT(*) AS n FROM users
            WHERE deleted_at IS NULL AND email_verified_at IS NOT NULL
            """
        )
        deleted = self._fetchone(
            "SELECT COUNT(*) AS n FROM users WHERE deleted_at IS NOT NULL"
        )
        queue = self._fetchall(
            """
            SELECT request_id, scope, status, counts, requested_at, completed_at
            FROM deletion_request ORDER BY requested_at DESC LIMIT 50
            """
        )
        for row in queue:
            row["counts"] = _load_json(row.get("counts"), {})
        return {
            "by_role": by_role,
            "verified": int(verified["n"]) if verified else 0,
            "deleted": int(deleted["n"]) if deleted else 0,
            "deletion_queue": queue,
        }

    # ---------------------------------------------------------- report inbox
    def reports_inbox(self, status: str | None = None) -> dict[str, Any]:
        """The problem-report inbox WITHOUT the free-text column: category +
        page/block reference + status is the triage signal (NFR-30)."""
        if status:
            rows = self._fetchall(
                """
                SELECT report_id, course_id, class_level, block_id, category,
                       status, created_at, resolved_at
                FROM problem_report WHERE status = %s
                ORDER BY created_at DESC LIMIT 100
                """,
                (status,),
            )
        else:
            rows = self._fetchall(
                """
                SELECT report_id, course_id, class_level, block_id, category,
                       status, created_at, resolved_at
                FROM problem_report
                ORDER BY created_at DESC LIMIT 100
                """
            )
        by_status = self._fetchall(
            "SELECT status, COUNT(*) AS n FROM problem_report GROUP BY status ORDER BY status"
        )
        by_category = self._fetchall(
            """
            SELECT category, COUNT(*) AS n FROM problem_report
            GROUP BY category ORDER BY category
            """
        )
        return {"rows": rows, "by_status": by_status, "by_category": by_category}

    def set_report_status(
        self, report_id: str, new_status: str
    ) -> dict[str, Any] | None:
        """EARS 4 of F-OPS-ADM-01: open → fixed → shipped-next-run. Mirrors
        API-A6's validation + audit row; the actor is the dashboard. The
        timestamp is an ISO string so the write is portable (API-A6 writes
        the same shape)."""
        if new_status not in REPORT_STATUSES:
            return None
        existing = self._fetchone(
            "SELECT status FROM problem_report WHERE report_id = %s", (report_id,)
        )
        if existing is None:
            return None
        resolved_at = _utc_now_iso() if new_status != "open" else None
        ok = self._execute(
            "UPDATE problem_report SET status = %s, resolved_at = %s WHERE report_id = %s",
            (new_status, resolved_at, report_id),
        )
        if not ok:
            return None
        self._execute(
            """
            INSERT INTO audit_log (audit_id, actor, action, target, before_hash, after_hash, at)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
            """,
            (
                uuid.uuid4().hex,
                "dashboard",
                "report.status",
                report_id,
                str(existing["status"]),
                new_status,
                _utc_now_iso(),
            ),
        )
        return {"before": str(existing["status"]), "after": new_status}

    # --------------------------------------------------------- flags & config
    def flags_view(self) -> dict[str, Any]:
        """The togglable guard profile (F-OPS-MET-01, DB-persisted) + its
        flip history from the audit log. Env-side flags are documented
        decisions rendered from DOCS, never read from this process's env —
        the dashboard pod does not host the backend's environment."""
        profile = self._fetchone(
            """
            SELECT mode, global_tranche, per_user_cap, demo_global_tranche,
                   demo_per_user_cap, warn_threshold_pct, total_budget_credits,
                   demo_reserve_pct, updated_at, updated_by
            FROM guard_profile WHERE id = 1
            """
        )
        flips = self._fetchall(
            """
            SELECT at, actor, target, before_hash, after_hash FROM audit_log
            WHERE action = 'guard_profile.flip' ORDER BY at DESC LIMIT 20
            """
        )
        return {"profile": profile, "flips": flips}


@dataclass
class EvalRunsStore:
    """ADM-10: read-only look into the eval evidence directory
    (`evals_runs/` in the repo, the `zivon-sources` PVC subPath `evals`
    in-cluster — `evals/store.py` writes it). Missing dir = honest empty."""

    base: Path = field(default_factory=eval_runs_dir)

    def available(self) -> bool:
        return self.base.is_dir()

    def _ledger_rows(self) -> list[dict[str, Any]]:
        ledger = self.base / "eval_runs_ledger.jsonl"
        if not ledger.is_file():
            return []
        rows: list[dict[str, Any]] = []
        try:
            for line in ledger.read_text(encoding="utf-8").splitlines():
                line = line.strip()
                if not line:
                    continue
                try:
                    rows.append(json.loads(line))
                except json.JSONDecodeError:
                    continue  # a torn tail line must not break the view
        except OSError:
            return []
        return rows

    def recent_runs(self, limit: int = 20) -> list[dict[str, Any]]:
        rows = self._ledger_rows()
        rows.reverse()  # the ledger is append-only; newest last
        return rows[:limit]

    def run_detail(self, run_id: str) -> dict[str, Any] | None:
        """One run's report cards. Path guard: slug regex + directory-entry
        equality — the run_id never enters Path construction."""
        if not _EVAL_RUN_ID_ALLOWED.fullmatch(run_id):
            return None
        base_dir = self.base.resolve()
        run_dir: Path | None = None
        try:
            entries = list(base_dir.iterdir())
        except OSError:
            return None
        for entry in entries:
            if entry.name == run_id and entry.is_dir():
                run_dir = entry
                break
        if run_dir is None:
            return None
        report_path = run_dir / "eval_report.json"
        if not report_path.is_file():
            return None
        try:
            report = json.loads(report_path.read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            return None
        if not isinstance(report, dict):
            return None
        return {
            "report": report,
            "cards": report.get("cards") or [],
            "summary": report.get("summary") or {},
        }
