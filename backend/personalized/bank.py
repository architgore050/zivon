"""The P2 question-bank seam for bank-first checks (agent-and-rag.md §6.1,
data-and-api.md §3 NEED-PL-09).

Read-only over the imported `question_bank` rows (migration `0004`): the
teaching agent never writes generated items back into the bank. Candidates
are pre-filtered deterministically — concept-scoped, level-mapped difficulty,
English (the teaching base language), reviewed/published only — and the
**stored answer/explanation always come from the row**, never from model
output (the decide call only selects which item fits; §4.4).
"""

from __future__ import annotations

import json
from typing import TYPE_CHECKING, Any, Final

if TYPE_CHECKING:
    from db.engine import DatabaseEngine

from .state import LEVEL_DIFFICULTY

BANK_STATUSES: Final[tuple[str, ...]] = ("reviewed", "published")
# Board-style (level 4) items are generated by the decide call in the
# board-exam style; the bank's hardest tier still feeds level 4 candidates.
BOARD_LEVEL: Final[int] = 4


class QuestionBank:
    """The `BankSource` implementation over `question_bank`."""

    def __init__(self, db: DatabaseEngine) -> None:
        self.db = db

    def candidates(
        self,
        concept_ids: list[str],
        level: int,
        *,
        limit: int = 6,
        language: str = "en",
    ) -> list[dict[str, Any]]:
        """Concept- and level-scoped candidates, deterministic order."""
        if not concept_ids:
            return []
        difficulty = LEVEL_DIFFICULTY.get(level)
        if difficulty is None:  # board level: the hardest tier feeds it
            difficulty = "hard"
        placeholders = ",".join("?" for _ in concept_ids)
        statuses = ",".join(f"'{s}'" for s in BANK_STATUSES)
        rows = self.db.fetchall(
            f"""
            SELECT question_id, base_item_id, concept_id, type, difficulty,
                   prompt, options, answer, explanation, misconception
            FROM question_bank
            WHERE concept_id IN ({placeholders})
              AND status IN ({statuses})
              AND language = ?
              AND difficulty = ?
            ORDER BY question_id
            LIMIT ?
            """,
            (*concept_ids, language, difficulty, max(1, limit)),
        )
        out: list[dict[str, Any]] = []
        for row in rows:
            options = _load_json(row.get("options")) or []
            out.append(
                {
                    "question_id": str(row["question_id"]),
                    "item_id": str(row["base_item_id"]),
                    "base_item_id": str(row["base_item_id"]),
                    "concept_id": str(row["concept_id"]),
                    "type": str(row["type"]),
                    "difficulty": str(row["difficulty"]),
                    "prompt": str(row["prompt"]),
                    "options": [str(o) for o in options],
                    "answer": _load_json(row.get("answer")) or {},
                    "explanation": str(row.get("explanation") or ""),
                    "misconception": row.get("misconception"),
                }
            )
        return out

    def item(self, item_id: str) -> dict[str, Any] | None:
        """One candidate by base_item_id (the decide call's selection)."""
        row = self.db.fetchone(
            """
            SELECT question_id, base_item_id, concept_id, type, difficulty,
                   prompt, options, answer, explanation, misconception
            FROM question_bank
            WHERE base_item_id = ? AND status IN ('reviewed', 'published')
            ORDER BY question_id
            """,
            (item_id,),
        )
        if row is None:
            return None
        return {
            "question_id": str(row["question_id"]),
            "item_id": str(row["base_item_id"]),
            "base_item_id": str(row["base_item_id"]),
            "concept_id": str(row["concept_id"]),
            "type": str(row["type"]),
            "difficulty": str(row["difficulty"]),
            "prompt": str(row["prompt"]),
            "options": [str(o) for o in (_load_json(row.get("options")) or [])],
            "answer": _load_json(row.get("answer")) or {},
            "explanation": str(row.get("explanation") or ""),
            "misconception": row.get("misconception"),
        }


def _load_json(value: object) -> Any:
    if value is None or isinstance(value, (dict, list)):
        return value
    try:
        return json.loads(str(value))
    except (TypeError, ValueError):
        return None
